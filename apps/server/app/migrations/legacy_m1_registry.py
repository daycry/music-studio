class Seed(TypeDecorator):
    """Decimal M1 canónico sin límite de entero SQLite."""

    impl = Text
    cache_ok = True

    def process_bind_param(self, value, dialect):
        if value is None:
            return None
        if isinstance(value, str) and value.isascii() and value.isdecimal():
            value = int(value)
        if type(value) is not int or value < 0:
            raise ValueError("Seed must be a non-negative integer")
        return str(value)

    def process_result_value(self, value, dialect):
        return None if value is None else int(value)


class ContractJSON(TypeDecorator):
    """Codec contractual M1 conservado para lecturas y restauración."""

    impl = JSON
    cache_ok = True

    def __init__(self, kind):
        super().__init__(none_as_null=True)
        self.kind = kind

    def process_bind_param(self, value, dialect):
        if value is None:
            return None
        return validate_contract(value, self.kind).model_dump(mode="json")

    def process_result_value(self, value, dialect):
        return None if value is None else validate_contract(value, self.kind)


class WorkerJSON(TypeDecorator):
    """Codec de publicación privada M1, sin modelos ORM futuros."""

    impl = JSON
    cache_ok = True

    def __init__(self, model):
        super().__init__(none_as_null=True)
        self.model = model

    def process_bind_param(self, value, dialect):
        return (
            None
            if value is None
            else self.model.model_validate(value).model_dump(mode="json")
        )

    def process_result_value(self, value, dialect):
        return None if value is None else self.model.model_validate(value)


